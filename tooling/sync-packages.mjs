import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { plugins, nodeRange, dshRange, suiteVersion } from './catalog.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const differences = [];
const runtime = readFileSync(join(root, 'tooling/provider-runtime.js'));
const filesField = ['index.js', 'lib', 'scripts', 'skills', 'examples', 'cordis.patch.yml', 'README.md', 'LICENSE', 'NOTICE.md', 'THIRD_PARTY_LICENSES'];
function update(path, content) {
  const bytes = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (existsSync(path) && readFileSync(path).equals(bytes)) return;
  if (check) differences.push(relative(root, path));
  else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, bytes); }
}
function walk(path) {
  if (!existsSync(path)) return [];
  return readdirSync(path, { withFileTypes: true }).flatMap((entry) => entry.isDirectory() ? walk(join(path, entry.name)) : [join(path, entry.name)]);
}
for (const plugin of plugins) {
  const folder = join(root, 'packages', plugin.name);
  const manifest = {
    name: plugin.name, version: plugin.version, description: plugin.description,
    type: 'module', main: './index.js', exports: { '.': './index.js' }, license: 'MIT',
    engines: { node: nodeRange, dsh: dshRange }, files: filesField,
    keywords: ['dsh-plugin', 'deepseek-harness', plugin.name.replace('dsh-', '')],
    dsh: { bundle: { patch: './cordis.patch.yml' } },
  };
  update(join(folder, 'package.json'), JSON.stringify(manifest, null, 2) + '\n');
  update(join(folder, 'cordis.patch.yml'), `- insert:\n    - id: ${plugin.name}-skills\n      name: ${plugin.name}\n`);
  update(join(folder, 'lib/provider.js'), runtime);
  update(join(folder, 'index.js'), `// Generated by tooling/sync-packages.mjs; package-local imports only.\nimport { definePlugin } from './lib/provider.js';\nconst plugin = definePlugin({ name: '${plugin.name}', skills: ${JSON.stringify(plugin.skills)}, baseURL: new URL('.', import.meta.url) });\nexport const { name, inject, skillNames, createProvider, apply } = plugin;\n`);
}
const suiteFolder = join(root, 'packages/dsh-workflow-suite');
const bundleFolder = join(suiteFolder, 'bundled');
if (!check) rmSync(bundleFolder, { recursive: true, force: true });
const expected = new Set();
for (const plugin of plugins) {
  const source = join(root, 'packages', plugin.name);
  const selected = ['index.js', 'LICENSE', 'NOTICE.md', 'lib', 'skills', 'scripts', 'THIRD_PARTY_LICENSES'];
  for (const item of selected) {
    const path = join(source, item);
    const candidates = ['lib', 'skills', 'scripts', 'THIRD_PARTY_LICENSES'].includes(item) ? walk(path) : existsSync(path) ? [path] : [];
    for (const file of candidates) {
      const target = join(bundleFolder, plugin.name, relative(source, file));
      expected.add(target);
      update(target, readFileSync(file));
    }
  }
}
if (check) for (const file of walk(bundleFolder)) if (!expected.has(file)) differences.push(relative(root, file) + ' (stale)');
update(join(suiteFolder, 'package.json'), JSON.stringify({
  name: 'dsh-workflow-suite', version: suiteVersion, description: 'Optional self-contained bundle of four DSH workflow plugins.',
  type: 'module', main: './index.js', exports: { '.': './index.js' }, license: 'MIT', engines: { node: nodeRange, dsh: dshRange },
  files: ['index.js', 'bundled', 'cordis.patch.yml', 'README.md', 'LICENSE', 'NOTICE.md'],
  keywords: ['dsh-plugin', 'deepseek-harness', 'suite'], dsh: { bundle: { patch: './cordis.patch.yml' } },
}, null, 2) + '\n');
update(join(suiteFolder, 'cordis.patch.yml'), '- insert:\n    - id: dsh-workflow-suite-skills\n      name: dsh-workflow-suite\n');
const imports = plugins.map((plugin, i) => `import * as family${i} from './bundled/${plugin.name}/index.js';`).join('\n');
const skillNames = plugins.flatMap((plugin) => plugin.skills);
update(join(suiteFolder, 'index.js'), `// Generated from the four standalone plugins; do not edit bundled copies.\n${imports}\nexport const name = 'dsh-workflow-suite';\nexport const inject = ['skills'];\nexport const skillNames = Object.freeze(${JSON.stringify(skillNames)});\nconst families = [${plugins.map((_, i) => 'family' + i).join(', ')}];\nexport async function apply(ctx, config = {}) {\n  const selected = config.enabledSkills ?? [...skillNames];\n  if (!Array.isArray(selected) || selected.some((value) => !skillNames.includes(value))) throw new Error('Invalid enabledSkills for dsh-workflow-suite.');\n  for (const family of families) {\n    const enabledSkills = family.skillNames.filter((value) => selected.includes(value));\n    if (enabledSkills.length) await ctx.plugin(family, { enabledSkills });\n  }\n}\n`);
if (differences.length) { console.error('Generated files need npm run sync:\n' + differences.join('\n')); process.exitCode = 1; }
else console.log(check ? 'Standalone metadata and generated suite are synchronized.' : 'Generated four package manifests and one self-contained suite.');
